const assert = require('node:assert/strict');
const C = require('../school-days/calendar.js');
assert.equal(C.count('2026-10-22','2026-10-23').school,1);
assert.equal(C.count('2026-10-23','2026-11-08').school,0);
assert.equal(C.count('2026-10-23','2026-11-09').school,1);
assert.equal(C.count('2026-12-17','2027-01-06').school,0);
assert.equal(C.count('2026-12-17','2027-01-07').school,1);
assert.equal(C.count('2027-03-19','2027-04-11').school,0);
assert.equal(C.count('2027-04-30','2027-05-03').school,0);
assert.equal(C.count('2027-04-30','2027-05-04').school,1);
assert.equal(C.count('2027-05-28','2027-06-06').school,0);
assert.equal(C.count('2027-06-25','2027-06-27').school,1);
assert.equal(C.count('2027-06-25','2027-06-27').special,1);
assert.equal(C.count('2027-07-07','2027-07-08').school,1);
assert.equal(C.count('2026-10-22','2026-10-22').school,0);
assert.equal(C.kind('2026-09-07',true),'school');
assert.equal(C.kind('2026-09-07',false),'holiday');
assert.throws(()=>C.parse('2027-02-30'));
assert.throws(()=>C.count('2026-10-22','2026-10-21'));
assert.throws(()=>C.count('2026-10-22','2027-07-09'));
assert.throws(()=>C.count('2026-08-01','2027-07-08'));
const full=C.count(C.start,C.end);
assert.equal(full.total,full.school+full.holiday+full.weekend);
